use crate::primitives::{DType, Literal};

#[derive(Debug)]
pub enum StackStatement {
    Push { value: Literal },
    Pop,
    Dup,
    Swap,
    Load { kind: DType },
    Store { kind: DType },
    Label { name: String },
    Jump { dest_name: String, dest_idx: Option<usize> },
    Jumpif { dest_name: String, dest_idx: Option<usize> },
    Call { dest_name: String, dest_idx: Option<usize>, t_in: Vec<DType>, t_out: Vec<DType> },
    Ret { t_out: Vec<DType>},
    Cast { to: DType },
    Conv { to: DType },

    Add,
    Sub,
    Div,
    Mult,
    Mod,
    Inc,
    Dec,
    And,
    Or,
    Not,
    Xor,
    Bsl,
    Bsr,
    Rol,
    Ror,
    Eq,
    Neq,
    Lt,
    Leq,
    Gt,
    Geq,
}
